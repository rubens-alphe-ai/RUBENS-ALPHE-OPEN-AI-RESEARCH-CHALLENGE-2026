#!/usr/bin/env python3
"""A French business test with answers no one can dispute, run on current models.

Every task is generated by this script from random parameters, and its answer
is computed by the same script from explicit rules stated in the task. Nothing
is graded by a model and nothing depends on a human key that could be wrong.
The tasks are new, so no model can have seen them.

Five areas, 60 tasks each:

- factures: the amount left to pay on an invoice (discount, two VAT rates,
  deposit already paid);
- service client: the decision a written refund policy imposes;
- rh: paid leave earned under a stated company rule;
- juridique: the last day of a deadline, with weekends and listed holidays;
- sante: one dose of a fictitious drug, with a daily cap and rounding.

Pre-registered in experiments/FR-BUSINESS-2026-10/PREREGISTRATION.md.

  python scripts/fr_business_bench.py --generate
  python scripts/fr_business_bench.py --run --config ~/.ra-psi/run-config.json --key openrouter
  python scripts/fr_business_bench.py --score
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import random
import re
import sys
from concurrent.futures import ThreadPoolExecutor
from datetime import date, timedelta
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
ROOT = SCRIPTS.parent
sys.path.insert(0, str(SCRIPTS))

EXPERIMENT = ROOT / "experiments" / "FR-BUSINESS-2026-10"
SEED = 20261003
PER_AREA = 60
MODELS = ["mistralai/mistral-medium-3.1", "openai/gpt-6.1-sol", "anthropic/claude-sonnet-5.5",
          "google/gemini-3.5-flash", "deepseek/deepseek-v4-pro", "openai/gpt-6-luna"]
BUDGET_USD = 22.0
MAX_TOKENS = 2000
INSTRUCTION = ("\n\nRéfléchis si besoin, puis termine ta réponse par une dernière ligne exactement de la forme :\n"
               "RÉPONSE : <ta réponse>")


def euros(x: Decimal) -> str:
    q = x.quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
    whole, cents = str(q).split(".")
    groups = []
    while len(whole) > 3:
        groups.insert(0, whole[-3:])
        whole = whole[:-3]
    groups.insert(0, whole)
    return "%s,%s €" % (" ".join(groups), cents)


def factures(rng: random.Random, k: int) -> dict:
    lines, ht20, ht55 = [], Decimal(0), Decimal(0)
    products = ["Ramette papier A4", "Cartouche d'encre", "Chaise de bureau", "Écran 27 pouces", "Clavier sans fil",
                "Livre technique", "Abonnement logiciel (mois)", "Câble HDMI", "Lampe de bureau", "Classeur"]
    for _ in range(rng.randint(2, 4)):
        name = rng.choice(products)
        qty = rng.randint(1, 12)
        unit = Decimal(rng.randint(150, 40000)) / 100
        rate = Decimal("5.5") if name == "Livre technique" else Decimal("20")
        total = (unit * qty).quantize(Decimal("0.01"))
        lines.append("- %s : %d × %s HT (TVA %s %%) = %s HT" % (name, qty, euros(unit), str(rate).replace(".", ","), euros(total)))
        if rate == 20:
            ht20 += total
        else:
            ht55 += total
    remise = Decimal(rng.choice([0, 5, 10, 15]))
    acompte = Decimal(rng.choice([0, 0, 50, 100, 250, 300]))
    f = (100 - remise) / 100
    base20, base55 = (ht20 * f).quantize(Decimal("0.01"), ROUND_HALF_UP), (ht55 * f).quantize(Decimal("0.01"), ROUND_HALF_UP)
    tva = (base20 * Decimal("0.20")).quantize(Decimal("0.01"), ROUND_HALF_UP) + (base55 * Decimal("0.055")).quantize(Decimal("0.01"), ROUND_HALF_UP)
    ttc = base20 + base55 + tva
    reste = ttc - acompte
    text = ("Facture n° F-2026-%04d\n%s\nRemise commerciale de %s %% sur l'ensemble des montants HT, appliquée avant TVA. "
            "La TVA est calculée par taux, sur les montants HT remisés, et chaque montant de TVA est arrondi au centime.\n"
            "Acompte déjà versé par le client : %s.\n\nQuestion : quel montant reste-t-il à payer (TTC, acompte déduit) ? "
            "Donne le montant en euros, au centime." % (rng.randint(1, 9999), "\n".join(lines), remise, euros(acompte)))
    return {"area": "factures", "prompt": text, "answer": str(reste.quantize(Decimal("0.01"))), "kind": "money"}


POLICY = ("Politique de retour de la boutique :\n"
          "1. Un produit défectueux signalé dans les 2 ans suivant l'achat est échangé (réponse B), "
          "sauf s'il a été réparé par un tiers : la demande est alors transférée au service technique (réponse D).\n"
          "2. Un produit non défectueux est remboursé (réponse A) s'il est retourné dans les 30 jours suivant l'achat, "
          "non utilisé et dans son emballage d'origine.\n"
          "3. Un produit non défectueux retourné entre 31 et 60 jours, non utilisé, est échangé (réponse B).\n"
          "4. Dans tous les autres cas, la demande est refusée (réponse C).\n"
          "Les délais se comptent en jours calendaires, le jour de l'achat n'étant pas compté.")


def service_client(rng: random.Random, k: int) -> dict:
    achat = date(2026, 1, 1) + timedelta(days=rng.randint(0, 200))
    delai = rng.choice([rng.randint(1, 29), 30, 31, rng.randint(32, 59), 60, 61, rng.randint(62, 900)])
    demande = achat + timedelta(days=delai)
    defect = rng.random() < 0.4
    tiers = defect and rng.random() < 0.3
    used = rng.random() < 0.4
    box = rng.random() < 0.7
    if defect:
        answer = "D" if tiers else ("B" if delai <= 730 else "C")
    elif not used and box and delai <= 30:
        answer = "A"
    elif not used and 31 <= delai <= 60:
        answer = "B"
    else:
        answer = "C"
    facts = ["acheté le %s" % achat.strftime("%d/%m/%Y"), "demande faite le %s" % demande.strftime("%d/%m/%Y"),
             "le produit %s" % ("ne s'allume plus (défaut)" if defect else "fonctionne parfaitement"),
             "il %s" % ("a été utilisé" if used else "n'a jamais été utilisé"),
             "il %s dans son emballage d'origine" % ("est" if box else "n'est plus")]
    if defect:
        facts.append("il %s par un réparateur indépendant" % ("a été réparé" if tiers else "n'a jamais été ouvert ni réparé"))
    rng.shuffle(facts)
    text = ("%s\n\nMessage du client : « Bonjour, j'ai un problème avec mon casque audio : %s. Que pouvez-vous faire ? »\n\n"
            "Question : quelle réponse la politique impose-t-elle ? A = rembourser, B = échanger, C = refuser, "
            "D = transférer au service technique. Réponds par une seule lettre." % (POLICY, " ; ".join(facts)))
    return {"area": "service client", "prompt": text, "answer": answer, "kind": "letter"}


def rh(rng: random.Random, k: int) -> dict:
    months = []
    for m in range(1, 13):
        worked = rng.choice([0, rng.randint(1, 14), 15, rng.randint(16, 22), 22, 22, 22])
        months.append(worked)
    complete = sum(1 for w in months if w >= 15)
    raw = Decimal("2.08") * complete
    half = (raw * 2).to_integral_value(rounding="ROUND_CEILING") / 2
    names = ["janvier", "février", "mars", "avril", "mai", "juin", "juillet", "août", "septembre", "octobre", "novembre", "décembre"]
    text = ("Règle de l'entreprise : chaque mois complet travaillé donne droit à 2,08 jours de congés. "
            "Un mois compte comme complet si le salarié y a travaillé au moins 15 jours. "
            "Le total annuel est arrondi au demi-jour supérieur (par exemple 10,40 devient 10,5 et 12,48 devient 12,5).\n\n"
            "Jours travaillés en 2026 : %s.\n\nQuestion : combien de jours de congés le salarié a-t-il acquis sur l'année ? "
            "Donne le nombre de jours." % "; ".join("%s %d" % (n, w) for n, w in zip(names, months)))
    return {"area": "rh", "prompt": text, "answer": str(half.normalize()), "kind": "number"}


HOLIDAYS_2026 = [date(2026, 1, 1), date(2026, 4, 6), date(2026, 5, 1), date(2026, 5, 8), date(2026, 5, 14),
                 date(2026, 5, 25), date(2026, 7, 14), date(2026, 8, 15), date(2026, 11, 1), date(2026, 11, 11),
                 date(2026, 12, 25)]


def juridique(rng: random.Random, k: int) -> dict:
    start = date(2026, 1, 5) + timedelta(days=rng.randint(0, 320))
    n = rng.choice([8, 10, 14, 15, 21, 30])
    end = start + timedelta(days=n)
    while end.weekday() >= 5 or end in HOLIDAYS_2026:
        end += timedelta(days=1)
    days = ["lundi", "mardi", "mercredi", "jeudi", "vendredi", "samedi", "dimanche"]
    text = ("Règle : le délai de %d jours calendaires court à compter du lendemain de la réception du courrier ; il expire "
            "le dernier jour à minuit. S'il expire un samedi, un dimanche ou un jour férié, il est prorogé jusqu'au premier "
            "jour ouvrable suivant. Jours fériés 2026 : %s.\n\nLe courrier a été reçu le %s %s.\n\nQuestion : quel est le "
            "dernier jour du délai ? Donne la date au format JJ/MM/AAAA."
            % (n, ", ".join(d.strftime("%d/%m") for d in HOLIDAYS_2026), days[start.weekday()], start.strftime("%d/%m/%Y")))
    return {"area": "juridique", "prompt": text, "answer": end.strftime("%d/%m/%Y"), "kind": "date"}


def sante(rng: random.Random, k: int) -> dict:
    weight = rng.randint(8, 110)
    per_kg = rng.choice([10, 15, 20])
    prises = rng.choice([2, 3, 4])
    cap = rng.choice([900, 1200, 1500])
    daily = min(weight * per_kg, cap)
    dose = math.floor(daily / prises / 25) * 25
    text = ("Médicament fictif « Zorvex » (exercice de calcul, aucun usage réel). Posologie : %d mg/kg/jour, répartis en "
            "%d prises égales. Dose maximale : %d mg par jour, quel que soit le poids. Chaque prise est arrondie au multiple "
            "de 25 mg inférieur.\n\nPatient : %d kg.\n\nQuestion : quelle est la dose d'une prise, en mg ?"
            % (per_kg, prises, cap, weight))
    return {"area": "sante", "prompt": text, "answer": str(dose), "kind": "number"}


AREAS = [factures, service_client, rh, juridique, sante]


def generate() -> list[dict]:
    rng = random.Random(SEED)
    items = []
    for make in AREAS:
        for k in range(PER_AREA):
            item = make(rng, k)
            item["id"] = "%s-%02d" % (item["area"].replace(" ", "_"), k)
            items.append(item)
    return items


def final_answer(text: str) -> str | None:
    found = re.findall(r"R[ÉE]PONSE\s*:\s*(.+)", text or "", re.I)
    return found[-1].strip().strip("*").strip() if found else None


def correct(item: dict, raw: str | None) -> int:
    if raw is None:
        return 0
    kind, truth = item["kind"], item["answer"]
    if kind == "letter":
        m = re.search(r"\b([ABCD])\b", raw.upper())
        return int(bool(m) and m.group(1) == truth)
    if kind == "date":
        m = re.search(r"(\d{1,2})/(\d{1,2})/(\d{4})", raw)
        return int(bool(m) and "%02d/%02d/%s" % (int(m.group(1)), int(m.group(2)), m.group(3)) == truth)
    cleaned = raw.replace(" ", "").replace(" ", "").replace(" ", "")
    m = re.search(r"-?\d+(?:[.,]\d+)?", cleaned)
    if not m:
        return 0
    value = Decimal(m.group(0).replace(",", "."))
    return int(abs(value - Decimal(truth)) < Decimal("0.005"))


def run(items: list[dict], config: Path, key: str, workers: int) -> None:
    import cost_guard
    from evaluate_experiment import AdapterError, call

    table = cost_guard.prices()
    est = 0.0
    for m in MODELS:
        if m not in table:
            raise SystemExit("no published price for %s" % m)
        est += sum(len(i["prompt"]) / 3.5 * table[m]["prompt"] + MAX_TOKENS * table[m]["completion"] for i in items)
    print(json.dumps({"pessimistic_usd": round(est, 2), "budget_usd": BUDGET_USD}), flush=True)
    if est > BUDGET_USD:
        raise SystemExit("estimate exceeds the pre-registered budget; refusing to run")
    location = json.loads(config.expanduser().read_text(encoding="utf-8")).get("keys", {}).get(key)
    if not location:
        raise SystemExit("no key location configured for %r" % key)

    def one(job):
        model, item = job
        path = EXPERIMENT / "raw" / model.replace("/", "_") / (item["id"] + ".json")
        if path.is_file():
            return
        entry = {"evaluator_id": model, "model": model, "endpoint": "https://openrouter.ai/api/v1/chat/completions",
                 "json_mode": False, "max_tokens": MAX_TOKENS, "extra_body": {"reasoning": {"effort": "low"}},
                 **{k: v for k, v in location.items() if k in ("api_key_file", "api_key_env")}}
        record = {"model": model, "item": item["id"], "attempts": []}
        for _ in range(2):
            try:
                content, served = call(entry, item["prompt"] + INSTRUCTION, MAX_TOKENS)
            except AdapterError as exc:
                record["attempts"].append({"error": str(exc)[:300]})
                continue
            record["attempts"].append({"content": content[-3000:], "served_model": served})
            record["answer"] = final_answer(content)
            if record["answer"] is not None:
                break
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(record, ensure_ascii=False, indent=1), encoding="utf-8")

    jobs = [(m, i) for i in items for m in MODELS]
    with ThreadPoolExecutor(max_workers=workers) as pool:
        list(pool.map(one, jobs))


def score(items: list[dict]) -> dict:
    rows, summary = [], {}
    for model in MODELS:
        folder = EXPERIMENT / "raw" / model.replace("/", "_")
        for item in items:
            path = folder / (item["id"] + ".json")
            record = json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}
            ok = correct(item, record.get("answer"))
            rows.append({"trial": model, "item": item["id"], "correct": ok, "area": item["area"],
                         "answered": record.get("answer") is not None, "missing": not path.is_file()})
    with (EXPERIMENT / "results.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=["trial", "item", "correct"])
        writer.writeheader()
        writer.writerows({k: r[k] for k in ("trial", "item", "correct")} for r in rows)
    for area in sorted({i["area"] for i in items}):
        with (EXPERIMENT / ("results-%s.csv" % area.replace(" ", "_"))).open("w", encoding="utf-8", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=["trial", "item", "correct"])
            writer.writeheader()
            writer.writerows({k: r[k] for k in ("trial", "item", "correct")} for r in rows if r["area"] == area)
    for model in MODELS:
        mine = [r for r in rows if r["trial"] == model]
        summary[model] = {"score": round(sum(r["correct"] for r in mine) / len(mine), 3),
                          "no_answer": sum(not r["answered"] for r in mine),
                          "missing": sum(r["missing"] for r in mine),
                          "by_area": {a: round(sum(r["correct"] for r in mine if r["area"] == a) /
                                              sum(1 for r in mine if r["area"] == a), 3)
                                      for a in sorted({i["area"] for i in items})}}
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--generate", action="store_true")
    parser.add_argument("--run", action="store_true")
    parser.add_argument("--score", action="store_true")
    parser.add_argument("--config", type=Path)
    parser.add_argument("--key", default="openrouter")
    parser.add_argument("--workers", type=int, default=8)
    args = parser.parse_args()
    items_path = EXPERIMENT / "items.json"
    if args.generate:
        EXPERIMENT.mkdir(parents=True, exist_ok=True)
        items_path.write_text(json.dumps(generate(), ensure_ascii=False, indent=1), encoding="utf-8")
        print("%d items written" % PER_AREA * 0 or "%d items written" % (PER_AREA * len(AREAS)))
    items = json.loads(items_path.read_text(encoding="utf-8"))
    if args.run:
        if not args.config:
            raise SystemExit("--run needs --config")
        run(items, args.config, args.key, args.workers)
    if args.score:
        summary = score(items)
        (EXPERIMENT / "summary.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
        print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
